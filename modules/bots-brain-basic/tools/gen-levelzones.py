#!/usr/bin/env python3
"""Generate data/levelzones.xml from the stock Mobius spawns (run from repo root).

A zone is a cluster of stock monster spawn territories near one of the five
starting villages whose monsters are all level 1..15. Re-run after spawn changes:
    python3 modules/bots-brain-basic/tools/gen-levelzones.py > modules/bots-brain-basic/data/levelzones.xml
"""
import glob, math, re, sys
import xml.etree.ElementTree as ET

DATA = "core/dist/game/data"
VILLAGES = {
    "TALKING_ISLAND": (-84318, 244579, -3730),
    "ELVEN": (46934, 51467, -2977),
    "DARK_ELVEN": (9745, 15606, -4574),
    "ORC": (-44836, -112524, -235),
    "DWARVEN": (115113, -178212, -901),
}
MAX_DIST = 24000   # territory centre to village centre (Dark Elf newbie grounds lie ~20k east)
MAX_LEVEL = 15
MERGE = 2200       # territories closer than this (and same band) are one zone

npcs = {}
for f in glob.glob(DATA + "/stats/npcs/*.xml"):
    for n in ET.parse(f).getroot().iter("npc"):
        ai = n.find("ai")
        npcs[int(n.get("id"))] = (int(n.get("level", "0")), n.get("type"), n.get("name"),
                                  ai is not None and ai.get("isAggressive") == "true")

terrs = []
for f in sorted(glob.glob(DATA + "/spawns/**/*.xml", recursive=True)):
    if "Quest" in f:
        continue
    root = ET.parse(f).getroot()
    if root.get("enabled") == "false":
        continue
    for sp in root.iter("spawn"):
        t = sp.find("territory")
        if t is None:
            continue
        nodes = [(int(n.get("x")), int(n.get("y"))) for n in t.iter("node")]
        if len(nodes) < 3:
            continue
        ids = [int(n.get("id")) for n in sp.findall("npc")]
        info = [npcs.get(i) for i in ids]
        if not ids or any(x is None or x[1] != "Monster" for x in info):
            continue
        lv = [x[0] for x in info]
        if max(lv) > MAX_LEVEL or min(lv) < 1:
            continue
        cx = sum(p[0] for p in nodes) / len(nodes); cy = sum(p[1] for p in nodes) / len(nodes)
        vil = min(VILLAGES, key=lambda v: math.dist((cx, cy), VILLAGES[v][:2]))
        if math.dist((cx, cy), VILLAGES[vil][:2]) > MAX_DIST:
            continue
        z = (int(t.get("minZ")) + int(t.get("maxZ"))) // 2
        r = max(math.dist((cx, cy), p) for p in nodes)
        cnt = sum(int(n.get("count", "1")) for n in sp.findall("npc"))
        terrs.append(dict(v=vil, x=cx, y=cy, z=z, r=r, lo=min(lv), hi=max(lv), n=cnt,
                          aggro=any(x[3] for x in info), ids=set(ids)))

def band(t):
    return 0 if t["hi"] <= 5 else (1 if t["hi"] <= 10 else 2)

zones = []
for t in terrs:
    for z in zones:
        if z["v"] == t["v"] and z["b"] == band(t) and any(math.dist((m["x"], m["y"]), (t["x"], t["y"])) < MERGE for m in z["m"]):
            z["m"].append(t); break
    else:
        zones.append(dict(v=t["v"], b=band(t), m=[t]))

out = ['<?xml version="1.0" encoding="UTF-8"?>',
       '<!-- Generated by tools/gen-levelzones.py from the stock spawns; do not edit by hand. -->',
       '<!-- A zone: centre/radius of its monster territories, monster level range, monsters, aggressive flag. -->',
       '<levelzones>']
zones.sort(key=lambda z: (z["v"], z["b"], -len(z["m"])))
count = {}
for z in zones:
    m = z["m"]; n = sum(t["n"] for t in m)
    if n < 4:
        continue
    w = n
    x = sum(t["x"] * t["n"] for t in m) / w; y = sum(t["y"] * t["n"] for t in m) / w
    zz = round(sum(t["z"] * t["n"] for t in m) / w)
    r = max(math.dist((x, y), (t["x"], t["y"])) + t["r"] for t in m)
    r = min(int(r), 3000)
    count[z["v"]] = count.get(z["v"], 0) + 1
    zid = "%s_%d" % (z["v"].lower(), count[z["v"]])
    ids = sorted(set().union(*[t["ids"] for t in m]))
    out.append('\t<zone id="%s" village="%s" x="%d" y="%d" z="%d" radius="%d" minLevel="%d" maxLevel="%d" monsters="%d" aggressive="%s" npcIds="%s" />'
               % (zid, z["v"], x, y, zz, r, min(t["lo"] for t in m), max(t["hi"] for t in m), n,
                  str(any(t["aggro"] for t in m)).lower(), ",".join(map(str, ids))))
out.append("</levelzones>")
print("\n".join(out))
print("zones: %d" % (len(out) - 5), file=sys.stderr)
