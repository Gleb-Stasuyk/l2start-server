#!/usr/bin/env python3
"""Generates data/market-items.xml: the items bots may trade (Living Worlds allow-list, src/.../lw/StoreEligibility.java)
with what the price model needs from stock CT0 data: name, kind, grade, NPC reference price, stackable, sold by an NPC
(any buylist) and the server stage (1-5) the item first shows up at.
Run from the repo root: python3 modules/economy-market/tools/gen-market-items.py"""
import glob, os, re, sys
import xml.etree.ElementTree as ET

# consumables the LW allow-list leaves out (LW traders sold drops and crafts) but our shot / potion traders need
EXTRA = [1835, 1463, 1464, 1465, 1466, 1467, 2509, 2510, 2511, 2512, 2513, 2514, 3947, 3948, 3949, 3950, 3951, 3952,
         1060, 1061, 1539, 736, 1831, 1832, 1833, 1834, 734, 735, 1374, 1375, 5592, 5591]
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
DATA = os.path.join(ROOT, 'core', 'dist', 'game', 'data')
MOD = os.path.join(ROOT, 'modules', 'economy-market')
GRADE_STAGE = {'NONE': 1, 'D': 1, 'C': 2, 'B': 3, 'A': 4, 'S': 5}

def stage(grade, price, name):
    if grade != 'NONE':
        return GRADE_STAGE[grade]
    m = re.search(r'\((Grade|grade)\s*([DCBAS])\)|Grade ([DCBAS])\b|\b([DCBAS])-Grade', name)
    g = next((x for x in (m.groups() if m else ()) if x and len(x) == 1), None)
    if g:
        return GRADE_STAGE[g]
    for limit, st in ((60000, 1), (400000, 2), (2000000, 3), (10000000, 4)):
        if price < limit:
            return st
    return 5

def main():
    src = open(os.path.join(MOD, 'src/org/l2start/economy/market/lw/StoreEligibility.java'), encoding='utf-8').read()
    body = src[src.index('INCLUDED_ITEM_IDS'):]
    ids = [int(x) for x in re.findall(r'\d+', body[body.index('{'):body.index('}')])]
    ids = sorted(set(ids) | set(EXTRA))
    items = {}
    for f in sorted(glob.glob(os.path.join(DATA, 'stats', 'items', '*.xml'))):
        for it in ET.parse(f).getroot().iter('item'):
            sets = {s.get('name'): s.get('val') for s in it.findall('set')}
            items[int(it.get('id'))] = (it.get('name'), it.get('type'), sets)
    titles = {}
    for f in glob.glob(os.path.join(DATA, 'stats', 'npcs', '*.xml')):
        for n in ET.parse(f).getroot().iter('npc'):
            titles[int(n.get('id'))] = n.get('title') or ''
    npc = set()  # sold by a stock merchant: the list names a stock NPC that is not a test-server helper (GM shop lists name none)
    for f in glob.glob(os.path.join(DATA, 'buylists', '*.xml')):
        root = ET.parse(f).getroot()
        sellers = [int(n.text) for n in root.iter('npc') if n.text and n.text.strip().isdigit()]
        if not any((s in titles) and ('Test Server' not in titles[s]) for s in sellers):
            continue
        for it in root.iter('item'):
            npc.add(int(it.get('id')))
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<!-- Generated by tools/gen-market-items.py from the LW allow-list and stock CT0 items/buylists. Do not edit by hand:',
           '     hand-made corrections go to data/market-overrides.xml. -->',
           '<market>']
    missing = []
    for i in ids:
        if i not in items:
            missing.append(i)
            continue
        name, kind, sets = items[i]
        grade = sets.get('crystal_type', 'NONE')
        price = int(sets.get('price', '0'))
        stack = sets.get('is_stackable', 'false') == 'true'
        nm = name.replace('&', '&amp;').replace('"', '&quot;').replace('<', '&lt;')
        out.append(f'\t<item id="{i}" name="{nm}" kind="{kind}" grade="{grade}" price="{price}" stackable="{str(stack).lower()}" npc="{str(i in npc).lower()}" stage="{stage(grade, price, name)}" />')
    out.append('</market>')
    with open(os.path.join(MOD, 'data', 'market-items.xml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{len(ids) - len(missing)} items, {len(missing)} ids not in CT0: {missing}', file=sys.stderr)

if __name__ == '__main__':
    main()
