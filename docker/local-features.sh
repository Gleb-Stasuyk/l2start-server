#!/bin/sh
# l2start "local" features generated from env (written by L2Launcher into .env / docker/.env). Sourced by entrypoint.sh (game role).
#   L2S_CLASS_MASTER     = off | any of 1,2,3 (e.g. "1,2,3")  -> stock Mobius ClassMaster popup (class-choice dialog at 20/40/76), free
#   L2S_STOCK_NPC_BUFFER = on|off   -> spawn stock Scheme Buffer NPC 50008 "Thiago" next to the gatekeepers of the main towns
#   L2S_ENCHANT_MAX      = N   -> maxEnchant of every scroll (EnchantItemData.xml) + upper bound of the rate groups
#   L2S_ENCHANT_CHANCE   = %   -> chance above the safe enchant (EnchantItemGroups.xml, stock 66)
#   L2S_BUFF_DURATION    = seconds  -> duration of every buff of the stock buffers (community board + scheme buffer); 0/empty = stock
# Community board buffer / GM shop on/off are plain ini keys (Custom/CommunityBoard.ini CommunityEnableBuffs / CommunityEnableMultisells).

lf_log() { echo "[entrypoint/local] $*"; }

lf_class_master() {
  v="${L2S_CLASS_MASTER:-}"
  [ -z "$v" ] && return 0
  f="$L2/game/config/ClassMaster.xml"
  enabled=false; opts=""
  for n in $(printf '%s' "$v" | tr ',' ' '); do
    case "$n" in
      1) cat=FIRST_CLASS_GROUP ;; 2) cat=SECOND_CLASS_GROUP ;; 3) cat=THIRD_CLASS_GROUP ;; *) continue ;;
    esac
    enabled=true
    opts="$opts
		<classChangeOption name=\"Free\">
			<appliesTo>
				<category>$cat</category>
			</appliesTo>
		</classChangeOption>"
  done
  cat > "$f" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- generated by docker/local-features.sh from L2S_CLASS_MASTER=$v -->
<list xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="../data/xsd/classMaster.xsd">
	<classMaster classChangeEnabled="$enabled" spawnClassMasters="false" showPopupWindow="$enabled">$opts
	</classMaster>
</list>
XML
  lf_log "class master: $v (enabled=$enabled)"
}

lf_npc_buffer() {
  f="$L2/game/data/spawns/Others/l2start_scheme_buffer.xml"
  case "${L2S_STOCK_NPC_BUFFER:-off}" in
    on|true|1)
      cat > "$f" <<'XML'
<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by docker/local-features.sh (L2S_STOCK_NPC_BUFFER=on): stock Scheme Buffer next to the gatekeepers -->
<list enabled="true" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="../../xsd/spawns.xsd">
	<spawn name="l2start_scheme_buffer">
		<npc id="50008" x="-12700" y="122811" z="-3114" heading="49152" respawnDelay="60" /> <!-- Gludio -->
		<npc id="50008" x="15680" y="143020" z="-2704" heading="32768" respawnDelay="60" /> <!-- Dion -->
		<npc id="50008" x="83561" y="147904" z="-3404" heading="16384" respawnDelay="60" /> <!-- Giran -->
		<npc id="50008" x="146836" y="25858" z="-2013" heading="0" respawnDelay="60" /> <!-- Aden -->
		<npc id="50008" x="148124" y="-55235" z="-2728" heading="48000" respawnDelay="60" /> <!-- Goddard -->
	</spawn>
</list>
XML
      lf_log "stock scheme buffer NPC: on (5 towns)" ;;
    *) rm -f "$f"; lf_log "stock scheme buffer NPC: off" ;;
  esac
}

lf_buff_duration() {
  d="${L2S_BUFF_DURATION:-0}"
  case "$d" in ''|0|*[!0-9]*) return 0 ;; esac
  cfg="$L2/game/config"
  ids=$( { tr -d '\r' < "$cfg/Custom/CommunityBoard.ini" | grep -E '^CommunityAvailableBuffs' | sed 's/^[^=]*=//' | tr ',' '\n';
           grep -oE '<buff[^>]*id="[0-9]+"' "$L2/game/data/SchemeBufferSkills.xml" 2>/dev/null | grep -oE 'id="[0-9]+"' | grep -oE '[0-9]+'; } \
         | tr -d ' ' | grep -E '^[0-9]+$' | sort -un )
  list=""
  for i in $ids; do list="$list$i,$d;"; done
  [ -z "$list" ] && { lf_log "buff duration: no buffer skills found"; return 0; }
  set_ini "$cfg/Player.ini" EnableModifySkillDuration True
  # SkillDurationList may span several lines ("\" continuation): drop the stock block first
  awk 'BEGIN{s=0} /^SkillDurationList[[:space:]]*=/{s=1} s==1{ if ($0 !~ /\\[[:space:]]*$/) s=0; next } {print}' "$cfg/Player.ini" > "$cfg/Player.ini.tmp" && mv "$cfg/Player.ini.tmp" "$cfg/Player.ini"
  printf '\nSkillDurationList = %s\n' "$list" >> "$cfg/Player.ini"
  lf_log "buff duration: ${d}s for $(echo "$ids" | wc -w) buffer skills"
}

lf_enchant() {
  d="$L2/game/data"
  m="${L2S_ENCHANT_MAX:-}"; c="${L2S_ENCHANT_CHANCE:-}"
  case "$m" in ''|*[!0-9]*) m="" ;; esac
  case "$c" in ''|*[!0-9]*) c="" ;; esac
  if [ -n "$m" ] && [ "$m" -ge 4 ] && [ "$m" -le 65000 ]; then
    sed -i -E "s/maxEnchant=\"[0-9]+\"/maxEnchant=\"$m\"/g" "$d/EnchantItemData.xml"
    sed -i -E "s/enchant=\"([0-9]+)-15\"/enchant=\"\1-$((m - 1))\"/g; s/enchant=\"16-65535\"/enchant=\"$m-65535\"/g" "$d/EnchantItemGroups.xml"
    lf_log "enchant max: +$m"
  fi
  if [ -n "$c" ] && [ "$c" -le 100 ]; then
    sed -i -E "s/chance=\"66\"/chance=\"$c\"/g" "$d/EnchantItemGroups.xml"
    lf_log "enchant chance: $c%"
  fi
}

apply_local_features() {
  lf_enchant
  lf_class_master
  lf_npc_buffer
  lf_buff_duration
}
